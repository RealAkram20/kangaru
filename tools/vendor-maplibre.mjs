/**
 * Vendors MapLibre GL into the driver app as a string module.
 *
 * The driver's maps are HTML documents inside a WebView, and each of them used
 * to fetch its library from `unpkg.com` on **every mount** — about 870 KB of
 * JavaScript and CSS, over whatever signal a boda has at the kerb. The WebView
 * cache hid that on a warm handset and did nothing on a cold one, an evicted
 * one, or the first run, which is the run a new driver judges the app by. That
 * fetch was the larger half of *"the map is too slow"* (ADR-0070).
 *
 * Writing the library out as a TypeScript module means the documents inline
 * it: it ships in the app bundle, loads from disk, and is there with no signal
 * at all. Only the vector tiles still come from the network.
 *
 * **Why MapLibre and not something smaller.** A raster map on Leaflet would be
 * a fifth of the size and need no WebGL, and ADR-0070 tried exactly that — but
 * CARTO's *raster* endpoint stamps every tile with "API KEY REQUIRED" while
 * its *vector* style is genuinely keyless, and no keyless raster basemap is
 * available to a commercial fleet. The library is the part we can fix without
 * a billing account; the renderer is not.
 *
 * Why a generated module and not an asset: Metro bundles `.js` as code, not
 * text, and the alternatives — an asset read with `expo-file-system` on first
 * use, or a config plugin copying files into `android/app/src/main/assets` —
 * each add an asynchronous step in front of a map that has to draw the moment
 * the screen settles. A string constant has none.
 *
 * `JSON.stringify` rather than a template literal, so nothing in a future
 * MapLibre release — a backtick, a `${` — can end the string it is written
 * into. The one thing no escaping can fix is `</script` inside the JS, which
 * would close the inline tag in the document; the build refuses that outright.
 *
 * Run from the repo root after bumping `maplibre-gl` in mobile/package.json:
 *   node tools/vendor-maplibre.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MOBILE = join(ROOT, 'mobile')
const OUT = join(MOBILE, 'src', 'trips', 'vendor', 'maplibre.ts')

const require_ = createRequire(join(MOBILE, 'package.json'))
const pkg = require_('maplibre-gl/package.json')
const dist = join(dirname(require_.resolve('maplibre-gl/package.json')), 'dist')

// The minified production build — the same file unpkg was serving. Not the
// `-csp` variant, which loads its worker from a second file and so cannot be
// inlined as one string.
const js = readFileSync(join(dist, 'maplibre-gl.js'), 'utf8')
const css = readFileSync(join(dist, 'maplibre-gl.css'), 'utf8')

if (/<\/script/i.test(js)) {
  throw new Error('maplibre-gl.js contains "</script" — it would close the inline tag in the map document')
}

const header = `
// GENERATED by tools/vendor-maplibre.mjs from maplibre-gl@${pkg.version} (${pkg.license}) — do not edit.
//
// MapLibre GL, inlined into the driver's map documents so the library ships in
// the app bundle instead of being fetched from a CDN on every mount
// (ADR-0070). Regenerate after bumping: node tools/vendor-maplibre.mjs
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(
  OUT,
  header +
    `export const MAPLIBRE_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export const MAPLIBRE_JS = ${JSON.stringify(js)};\n` +
    `export const MAPLIBRE_CSS = ${JSON.stringify(css)};\n`,
)

console.log(`wrote ${OUT} (maplibre-gl@${pkg.version}: ${js.length} B js, ${css.length} B css)`)
