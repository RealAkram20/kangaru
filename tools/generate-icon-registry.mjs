/**
 * Regenerates `frontend/src/components/core/iconRegistry.ts`.
 *
 * `Icon` takes a name at runtime (`<Icon name="map-pin" />`), which used to
 * mean `import { icons } from 'lucide-react'` — a dictionary of all ~1756
 * icons that no bundler can tree-shake. That cost 467,925 bytes, 34% of the
 * main chunk, to render the ~126 icons this app actually names.
 *
 * This scans src/ for every string literal matching a Lucide name and writes
 * an explicit map built from named imports, which *is* tree-shakeable.
 *
 * It over-includes: any string that happens to match a Lucide name ('circle',
 * 'table', 'type') is kept even when it was a CSS value. That is deliberate —
 * a name missing from the map renders as a grey placeholder, a silent visual
 * bug, whereas a spare icon costs a few hundred bytes.
 *
 * Run from the repo root after adding an icon:
 *   node tools/generate-icon-registry.mjs
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'frontend', 'src')
const OUT = join(SRC, 'components', 'core', 'iconRegistry.ts')

const require_ = createRequire(join(ROOT, 'frontend', 'package.json'))
const entry = require_.resolve('lucide-react')
const lucide = await import('file:///' + entry.replace(/\\/g, '/'))

const pascalNames = new Set(Object.keys(lucide.icons ?? {}))
if (pascalNames.size === 0) {
  throw new Error('lucide-react exported no icons — is it installed in frontend/?')
}

/*
 * Kebab names come from the shipped icon filenames, not from transforming the
 * PascalCase exports.
 *
 * Deriving them was wrong in a way that failed silently: `Building2` becomes
 * `building2` under any plain camel-to-kebab rule, but Lucide's real name —
 * and the one this app writes — is `building-2`. Every digit-bearing icon was
 * dropped from the registry and rendered as a grey placeholder box.
 * `dist/esm/icons/building-2.mjs` is the authority, so read that.
 */
const iconDir = join(dirname(entry), '..', 'esm', 'icons')
const kebabNames = existsSync(iconDir)
  ? readdirSync(iconDir)
      .filter((f) => f.endsWith('.mjs') && !f.endsWith('.d.mjs'))
      .map((f) => f.slice(0, -4))
  : []
if (kebabNames.length === 0) {
  throw new Error(`no icon modules found under ${iconDir} — has lucide-react's layout changed?`)
}

/** "building-2" -> "Building2". Unambiguous in this direction. */
const pascalOf = (kebab) =>
  kebab
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

// Keep only names whose component is really exported: the icons directory also
// carries aliases and deprecated names that `icons` does not list.
const kebabToPascal = new Map()
for (const kebab of kebabNames) {
  const pascal = pascalOf(kebab)
  if (pascalNames.has(pascal)) kebabToPascal.set(kebab, pascal)
}

const files = []
;(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(tsx?|jsx?)$/.test(entry)) files.push(p)
  }
})(SRC)

const found = new Set()
const literalRe = /['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g
for (const file of files) {
  if (file === OUT) continue
  const src = readFileSync(file, 'utf8')
  let m
  while ((m = literalRe.exec(src))) if (kebabToPascal.has(m[1])) found.add(m[1])
}

const pairs = [...found].sort().map((k) => [k, kebabToPascal.get(k)])

writeFileSync(
  OUT,
  `// GENERATED by tools/generate-icon-registry.mjs — do not hand-edit.
//
// \`import { icons } from 'lucide-react'\` pulls all ${pascalNames.size} icons into the
// bundle: a runtime dictionary lookup cannot be tree-shaken. That measured
// 467,925 bytes, 34% of the main chunk, for the ${pairs.length} icons this app names.
// Named imports are tree-shakeable, so only these ship.
//
// Regenerate after adding an icon:  node tools/generate-icon-registry.mjs

import type { LucideIcon } from 'lucide-react'
import {
${pairs.map(([, p]) => `  ${p},`).join('\n')}
} from 'lucide-react'

/** Kebab-case Lucide name -> component, for the names this app uses. */
export const ICON_REGISTRY: Record<string, LucideIcon> = {
${pairs.map(([k, p]) => `  '${k}': ${p},`).join('\n')}
}
`,
  'utf8',
)

console.log(`wrote ${OUT}`)
console.log(`${pairs.length} icons of ${pascalNames.size} available`)
